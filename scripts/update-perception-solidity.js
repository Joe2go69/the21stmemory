// Sanity: no other topics should have been given these image paths (unique ownership)
function collectImageFields(topics, out = []) {
  for (const t of topics) {
    for (const key of ['topic_image', 'infographic_image', 'pdf_preview_image']) {
      if (t[key]) out.push({ id: t.id, key, path: t[key] });
    }
    if (t.subtopics) collectImageFields(t.subtopics, out);
  }
  return out;
}

const ours = new Set([
  perceptionSolidity.topic_image,
  perceptionSolidity.infographic_image,
  perceptionSolidity.pdf_preview_image
]);
const collisions = collectImageFields(source.topics).filter(
  (e) => e.id !== 'perception-solidity' && ours.has(e.path)
);
if (collisions.length) {
  throw new Error(
    'Image path collision with other topics:\n' +
      collisions.map((c) => `${c.id}.${c.key} = ${c.path}`).join('\n')
  );
}

// Ensure we did not overwrite other topics' image fields (spot-check: only perception-solidity owns these paths)
const allImageEntries = collectImageFields(source.topics);
const pathOwners = new Map();
for (const e of allImageEntries) {
  if (!pathOwners.has(e.path)) pathOwners.set(e.path, []);
  pathOwners.get(e.path).push(`${e.id}.${e.key}`);
}
for (const p of ours) {
  const owners = pathOwners.get(p) || [];
  if (owners.length !== 1 || !owners[0].startsWith('perception-solidity.')) {
    throw new Error(`Unexpected owners for ${p}: ${owners.join(', ')}`);
  }
}

// Ensure placeholder.webp still used by others (we did not clobber their paths by mistake)
const placeholderOwners = (pathOwners.get('images/breakdown/placeholder.webp') || []).filter(
  (o) => !o.startsWith('perception-solidity.')
);
if (placeholderOwners.length === 0) {
  console.warn('Warning: no other topics still use placeholder.webp (unexpected but not fatal)');
}

